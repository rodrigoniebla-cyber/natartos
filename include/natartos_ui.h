static inline void nui_put(int x, int y, nui_rgb c) {
    if ((unsigned)x >= FB_W || (unsigned)y >= FB_H) return;
    unsigned char *p = nui_px + ((size_t)y * FB_W + x) * 4;
    p[0] = c.b; p[1] = c.g; p[2] = c.r; p[3] = 255;
}

static void nui_rect(int x, int y, int w, int h, nui_rgb c) {
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > FB_W) w = FB_W - x;
    if (y + h > FB_H) h = FB_H - y;
    if (w <= 0 || h <= 0) return;
    for (int yy = y; yy < y + h; yy++) {
        unsigned char *p = nui_px + ((size_t)yy * FB_W + x) * 4;
        for (int xx = 0; xx < w; xx++, p += 4) { p[0] = c.b; p[1] = c.g; p[2] = c.r; p[3] = 255; }
    }
}

/* filled rounded rect */
static void nui_rrect(int x, int y, int w, int h, int r, nui_rgb c) {
    for (int yy = 0; yy < h; yy++) {
        int inset = 0;
        int dy = yy < r ? r - yy : (yy >= h - r ? yy - (h - r - 1) : 0);
        if (dy) while (inset < r && (r - inset) * (r - inset) + dy * dy > r * r) inset++;
        nui_rect(x + inset, y + yy, w - 2 * inset, 1, c);
    }
}

static int nui_text_w(const char *s, int sc) {
    int n = (int)strlen(s);
    return n ? n * 6 * sc - sc : 0;
}

static void nui_text(const char *s, int x, int y, int sc, nui_rgb c) {
    for (; *s; s++, x += 6 * sc) {
        int ch = (unsigned char)*s;
        if (ch >= 'a' && ch <= 'z') ch -= 32;
        if (ch < 32 || ch > 95) ch = '?';
        const unsigned char *g = NUI_FONT[ch - 32];
        for (int r = 0; r < 7; r++)
            for (int col = 0; col < 5; col++)
                if (g[r] & (0x10 >> col)) nui_rect(x + col * sc, y + r * sc, sc, sc, c);
    }
}

/* draw at most max_w pixels wide, ending in ".." when cut */
static void nui_text_clip(const char *s, int x, int y, int sc, int max_w, nui_rgb c) {
    char buf[128];
    snprintf(buf, sizeof buf, "%s", s);
    if (nui_text_w(buf, sc) > max_w) {
        size_t n = strlen(buf);
        while (n > 2 && nui_text_w(buf, sc) > max_w) { buf[--n] = 0; buf[n - 1] = '.'; buf[n - 2] = '.'; }
    }
    nui_text(buf, x, y, sc, c);
}

